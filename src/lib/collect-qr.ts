/**
 * 등록 QR — **현장 입장에 쓰이므로 스캔 실패가 곧 줄이다** (설계 §9.2).
 *
 * 규칙을 여기 한 곳에 모은 이유: QR 이 나가는 자리가 셋이다(완료 화면·티켓 페이지·이메일).
 * 자리마다 옵션을 적으면 한 곳만 고쳐지고, 그 차이는 **현장에서 스캐너가 안 읽힐 때**
 * 처음 드러난다. 아래 옵션은 전부 근거가 있는 값이라 임의로 바꾸지 말 것.
 *
 * ── 절대 규칙(§9.2) ────────────────────────────────────────────────────
 *  · **배경은 불투명 흰색.** 투명 PNG 금지 — 다크 UI 에 올리면 검은 모듈이 검은 배경에
 *    놓여 대비가 사라진다. 다크모드 QR 사고의 대부분이 이것이다.
 *  · **반전 금지.** 표준 리더는 어두운 모듈/밝은 배경을 전제한다.
 *  · **여백(quiet zone) 4모듈 이상.** 규격 요구사항. 0으로 만드는 생성기가 흔한데
 *    여백이 없으면 인식률이 급락한다. 이미지 안의 4모듈만으로 끝내지 말고 **표시하는
 *    자리에서 흰 패딩을 한 겹 더 깐다** — QR_WHITE_PAD_PX 주석에 이유와 계산이 있다.
 *  · **오류정정 레벨 Q.** 반사·지문·구김·인쇄 번짐을 견딘다. 13자리는 짧아서 Q 로 올려도
 *    조밀해지지 않는다.
 *  · **순수 흑백.** 컬러 QR 은 대비가 낮고 **흑백 열전사 프린터에서 뭉갠다** — 배지를
 *    직접 출력하므로 특히 중요하다.
 *  · 로고 오버레이 금지(기본).
 *
 * ── 담는 값 ────────────────────────────────────────────────────────────
 * **등록번호만.** 현장은 전용 HID 스캐너를 쓰는데(§12), URL 을 읽으면 긴 문자열이 그대로
 * 입력돼 처리가 번거롭다. 우리 앱은 둘 다 인식한다(extractRegistrationNo).
 */
import QRCode from "qrcode";

/** 화면 최소 200×200px(§9.2). 인쇄는 2cm 이상 — 그건 CSS·PDF 쪽 책임이다. */
export const QR_MIN_DISPLAY_PX = 200;

/**
 * QR 이미지 **바깥**에 한 겹 더 까는 흰 여백(CSS px). 표시하는 쪽이 카드 패딩으로 준다.
 *
 * ── 왜 이미지 안의 4모듈로 끝내지 않나 ────────────────────────────────
 * 200px 로 표시할 때 이미지 안의 여백은 200 × 4/29 ≈ 27.6px 이다. 고해상도 폰
 * (1 CSS px ≈ 0.16mm)에서 4.4mm, 데스크톱(96ppi 기준 0.265mm)에서 7.3mm — 현장에서
 * 말하는 3mm 를 이미 넘는다. 그런데 이 27.6px 이 버티지 못하는 자리가 둘 있다:
 *  · **다크 배경.** 카드 배경이 어두우면 QR 자체 여백이 흰색의 **전부**다. 여유가 없다.
 *  · **축소.** 호스트 CSS·메일 클라이언트가 이미지를 줄이면 여백도 같은 비율로 준다 —
 *    절반으로 줄면 2.2mm 라 3mm 밑으로 떨어진다.
 *
 * ── 왜 margin 모듈 수를 올리지 않나 ──────────────────────────────────
 * 표시 폭이 고정이라 모듈을 늘리면 **심볼이 그만큼 작아진다**(4→6모듈이면 145px → 127px).
 * 스캐너에게 이미지 안의 여백과 카드의 흰 패딩은 구분되지 않는 같은 흰색이므로, 여백은
 * 바깥에서 늘리고 심볼 크기는 지키는 쪽이 이득이다.
 *
 * 20px 은 그 자체만으로 폰에서 3.2mm·데스크톱에서 5.3mm 다. 이미지 여백과 합치면
 * 각각 7.6mm·12.6mm — 절반으로 축소돼도 3.8mm 가 남는다.
 *
 * **쓰는 쪽에서 이 상수를 import 하지 않는다.** css.ts 는 파트너 사이트에 그대로
 * 주입되는 문자열이라 여기를 참조하면 `qrcode` 패키지가 브라우저 번들에 딸려 온다.
 * QR_MIN_DISPLAY_PX(200px)과 같은 방식으로, 값은 여기에 적고 표시하는 쪽에는 리터럴을
 * 두되 이 상수를 가리키는 주석을 단다.
 */
export const QR_WHITE_PAD_PX = 20;

/**
 * 공통 옵션. `margin` 은 **모듈 수**다(픽셀이 아니다) — 4가 규격 최소치.
 * `color.light` 를 불투명 흰색(#ffffffff)으로 못 박는 것이 투명 배경 사고를 막는 지점이다.
 */
const BASE = {
  errorCorrectionLevel: "Q",
  margin: 4,
  color: { dark: "#000000ff", light: "#ffffffff" },
} as const;

/**
 * PNG 버퍼. 이메일 첨부와 이미지 라우트가 쓴다.
 *
 * `width` 는 **최종 픽셀 폭**이다. 인쇄 배지에서 뭉개지지 않게 화면 최소치의 배수로 뽑는다 —
 * 브라우저가 축소하는 것은 안전하지만 확대는 계단이 보인다.
 */
export async function qrPngBuffer(text: string, width = 512): Promise<Buffer> {
  return QRCode.toBuffer(text, { ...BASE, type: "png", width });
}

/**
 * SVG 문자열. 티켓 페이지처럼 해상도가 자유로운 곳에서 쓴다.
 * 이메일에는 쓰지 않는다 — 상당수 클라이언트가 SVG 를 막는다(§9.3 은 PNG 첨부를 요구).
 */
export async function qrSvgString(text: string): Promise<string> {
  return QRCode.toString(text, { ...BASE, type: "svg", width: 512 });
}
