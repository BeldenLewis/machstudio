/**
 * `<script>` 안에 넣어도 안전한 JSON.
 *
 * 세 가지를 막는다:
 *  · `</script>` 브레이크아웃 — 운영자가 쓴 안내 문구 한 줄로 파트너 페이지에 임의
 *    스크립트가 들어간다. 우리 오리진에서 서빙되는 스크립트 본문이라 파트너의 CSP
 *    allowlist 도 통과한다.
 *  · U+2028 / U+2029 — JS 문자열 리터럴을 깨는 문자다. JSON 에서는 유효하지만
 *    스크립트 본문에 그대로 들어가면 구문 오류가 된다.
 *
 * ── 이 규칙이 저장소에 여섯 벌 있었다 ────────────────────────────────
 * `/f`·`/c`·`/cp`·`/w/l` 로더가 각자 같은 함수를 들고 있다. 보안 규칙이 복사돼 있으면
 * 한 곳만 고쳐지고 그 차이는 파트너 페이지에서 처음 드러난다. 새 코드는 이걸 쓰고,
 * 기존 여섯 곳을 여기로 모으는 것은 별건으로 남긴다(라이브 경로를 한 번에 건드리지 않는다).
 */
export function jsonForScript(value: unknown): string {
  return JSON.stringify(value)
    .replace(/</g, "\\u003C")
    .replace(/>/g, "\\u003E")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}
